# -*- coding: utf-8 -*-
"""舌脉消融的唯一权威定义（single source of truth）。

背景：历史上 build_eval_set.py 与 build_tasks23.py 各自内联了一份
strip 正则，窗口宽度不同（{0,10}/{0,20} vs {0,12}/{0,24}），导致
同一批病例出现两份不一致的"去舌脉文本"（6906 例中 81 例不同，
最宽处多删 11 字，且多删的内容并非舌脉，例如把"肺部感染"删成"肺"）。
消融分析要求"只移除舌脉信息、其余保持不变"，窗口过宽会误删非舌脉
内容，从而把"信息丢失"错误归因给舌脉。

本模块采用更精确的窄窗口版本，作为 T1 与消融任务共用的唯一实现。
"""
import re

TONGUE = re.compile(r"[^。；;，,]{0,10}(舌[^。；;，,]{0,20})")
PULSE = re.compile(r"[^。；;，,]{0,10}(脉[^。；;，,]{0,20})")


def strip_tongue_pulse(t: str) -> str:
    """移除与舌象/脉象相关的最小完整分句，合并重复顿号并清理首尾标点。"""
    t2 = TONGUE.sub("", t)
    t2 = PULSE.sub("", t2)
    return re.sub(r"[，,]{2,}", "，", t2).strip("，。； ")
